export function getBookBySlug(slug) {
  if (!slug) return INDIA_GK_TREE;
  const found = BOOKS_CATALOG.find((b) => b.slug === slug || b.id === slug);
  if (found && found.tree) return found.tree;
  if (slug === "world-gk") return WORLD_GK_TREE;
  return INDIA_GK_TREE;
}

/**
 * Sanitizes input text allowing strictly only <b> and <i> HTML tags.
 * Replaces all other tags with empty strings or escaped entities.
 */
export function sanitizeHtml(raw) {
  if (!raw || typeof raw !== "string") return "";
  // 1. Match allowed tags: <b>, </b>, <i>, </i>
  const tokens = [];
  const regex = /(<\/?b>|<\/?i>)/gi;
  let lastIndex = 0;
  let match;

  while ((match = regex.exec(raw)) !== null) {
    if (match.index > lastIndex) {
      // Escape HTML in the text part
      const textChunk = raw.substring(lastIndex, match.index);
      tokens.push(escapeHtml(textChunk));
    }
    tokens.push(match[0].toLowerCase());
    lastIndex = regex.lastIndex;
  }
  if (lastIndex < raw.length) {
    tokens.push(escapeHtml(raw.substring(lastIndex)));
  }
  return tokens.join("");
}

function escapeHtml(str) {
  return str
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}

/**
 * Calculates star rating:
 * >= 90% -> 3 stars
 * >= 70% -> 2 stars
 * >= 40% -> 1 star
 * < 40% -> 0 stars
 */
export function calculateStars(score, total) {
  if (!total || total <= 0) return 0;
  const p = (score / total) * 100;
  return p >= 90 ? 3 : p >= 70 ? 2 : p >= 40 ? 1 : 0;
}
